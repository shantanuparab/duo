const W = 16, H = 16;

function darkenColor(hex, amount = 0.3) {
  const c = hex.replace("#", "");
  const r = Math.max(0, Math.round(parseInt(c.substring(0, 2), 16) * (1 - amount)));
  const g = Math.max(0, Math.round(parseInt(c.substring(2, 4), 16) * (1 - amount)));
  const b = Math.max(0, Math.round(parseInt(c.substring(4, 6), 16) * (1 - amount)));
  return `rgb(${r},${g},${b})`;
}

function renderPetToOffscreen(type, state, size) {
  const pet = PETS[type] || PETS.cat;
  const colors = PET_COLORS[type] || PET_COLORS.cat;
  const frame = pet[state] || pet.idle;

  const canvas = document.createElement("canvas");
  canvas.width = W * size;
  canvas.height = H * size;
  const ctx = canvas.getContext("2d");

  const resolved = [];
  for (let y = 0; y < H; y++) {
    resolved[y] = [];
    for (let x = 0; x < W; x++) {
      const v = frame[y]?.[x];
      if (!v) { resolved[y][x] = null; continue; }
      const color = colors[v] || "#ff00ff";
      resolved[y][x] = color;
      ctx.fillStyle = color;
      ctx.fillRect(x * size, y * size, size, size);
    }
  }

  // Outline pass
  for (let y = 0; y < H; y++) {
    for (let x = 0; x < W; x++) {
      if (resolved[y][x]) continue;
      const neighbors = [[y-1,x],[y+1,x],[y,x-1],[y,x+1]];
      for (const [ny, nx] of neighbors) {
        if (ny >= 0 && ny < H && nx >= 0 && nx < W && resolved[ny]?.[nx]) {
          ctx.fillStyle = darkenColor(resolved[ny][nx]);
          ctx.fillRect(x * size, y * size, size, size);
          break;
        }
      }
    }
  }

  return canvas;
}

export default function PixelPet({ type = "cat", state = "idle", size = 5, className = "" }) {
  const canvasRef = useRef(null);
  const cacheRef = useRef(null);
  const cacheKeyRef = useRef("");

  useEffect(() => {
    const canvas = canvasRef.current;
    if (!canvas) return;

    canvas.width = W * size;
    canvas.height = H * size;

    const key = `${type}-${state}-${size}`;
    if (cacheKeyRef.current !== key) {
      cacheRef.current = renderPetToOffscreen(type, state, size);
      cacheKeyRef.current = key;
    }

    const ctx = canvas.getContext("2d");
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    ctx.drawImage(cacheRef.current, 0, 0);
  }, [type, state, size]);

  return (
    <canvas
      ref={canvasRef}
      className={`pixel-pet ${className}`}
      style={{ width: W * size, height: H * size, imageRendering: "pixelated" }}
    />
  );
}
